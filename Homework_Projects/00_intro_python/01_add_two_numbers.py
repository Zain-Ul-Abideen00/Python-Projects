# Add Two Numbers
# This program takes two numbers as input and displays their sum

def main():
    # Get input from user
    num1 = int(input("Enter first number: "))
    num2 = int(input("Enter second number: "))

    # Calculate sum
    total = num1 + num2

    # Display result
    print(f"The sum of {num1} and {num2} is {total}")

if __name__ == '__main__':
    main()
